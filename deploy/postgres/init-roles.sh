#!/usr/bin/env bash
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  DO \$\$
  BEGIN
    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${POSTGRES_MIGRATOR_USER}') THEN
      CREATE ROLE ${POSTGRES_MIGRATOR_USER} WITH LOGIN PASSWORD '${POSTGRES_MIGRATOR_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${POSTGRES_RUNTIME_USER}') THEN
      CREATE ROLE ${POSTGRES_RUNTIME_USER} WITH LOGIN PASSWORD '${POSTGRES_RUNTIME_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
    END IF;
  END
  \$\$;

  GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${POSTGRES_MIGRATOR_USER}, ${POSTGRES_RUNTIME_USER};
  GRANT USAGE, CREATE ON SCHEMA public TO ${POSTGRES_MIGRATOR_USER};
  GRANT USAGE ON SCHEMA public TO ${POSTGRES_RUNTIME_USER};
  ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_MIGRATOR_USER} IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${POSTGRES_RUNTIME_USER};
  ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_MIGRATOR_USER} IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO ${POSTGRES_RUNTIME_USER};
EOSQL
